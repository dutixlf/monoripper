const buckets = [0.005, 0.01, 0.025, 0.05, 0.1, 0.25, 0.5, 1, 2.5, 5, 10, 30]
const methods = new Set(['GET', 'HEAD', 'POST', 'PUT', 'PATCH', 'DELETE', 'OPTIONS'])
const maxWorkerBytes = 1024 * 1024
const metricName = /^[a-zA-Z_:][a-zA-Z0-9_:]*$/
const escape = (value: string) => value.replace(/\\/g, '\\\\').replace(/\n/g, '\\n').replace(/"/g, '\\"')
const labels = (pairs: Record<string, string>) => '{' + Object.entries(pairs).map(([key, value]) => `${key}="${escape(value)}"`).join(',') + '}'

interface Family { help?: string; type: string; samples: string[] }
export interface ScrapeTarget { context: string; pid: number; port: number; token: string }
export interface RuntimeGauges {
  project: string; environment: string; ready: boolean
  contexts: { name: string; desiredReplicas: number; readyReplicas: number; restarts: number; inFlight: number }[]
}

/** Gateway request accounting. Labels are context/method/status only: no paths, clients or identities. */
export class GatewayMetrics {
  private requests = new Map<string, number>()
  private errors = new Map<string, number>()
  private durations = new Map<string, { counts: number[]; sum: number; count: number }>()
  private scrapeErrors = new Map<string, number>()

  observe(context: string, method: string, status: number, seconds: number): void {
    const key = [context, methods.has(method) ? method : 'OTHER', String(status)].join('\0')
    this.requests.set(key, (this.requests.get(key) ?? 0) + 1)
    const histogram = this.durations.get(context) ?? { counts: buckets.map(() => 0), sum: 0, count: 0 }
    buckets.forEach((bound, index) => { if (seconds <= bound) histogram.counts[index]!++ })
    histogram.sum += seconds
    histogram.count++
    this.durations.set(context, histogram)
  }
  gatewayError(context: string, code: string): void {
    const key = `${context}\0${code}`
    this.errors.set(key, (this.errors.get(key) ?? 0) + 1)
  }

  async render(gauges: RuntimeGauges, targets: ScrapeTarget[]): Promise<string> {
    const out: string[] = []
    const family = (name: string, type: string, help: string, samples: string[]) => {
      out.push(`# HELP ${name} ${help}`, `# TYPE ${name} ${type}`, ...samples)
    }
    family('monoripper_info', 'gauge', 'Runtime identity.', [`monoripper_info${labels({ project: gauges.project, environment: gauges.environment })} 1`])
    family('monoripper_ready', 'gauge', '1 when every enabled context has a ready replica.', [`monoripper_ready ${gauges.ready ? 1 : 0}`])
    family('monoripper_context_replicas_desired', 'gauge', 'Desired replicas per context.', gauges.contexts.map(c => `monoripper_context_replicas_desired${labels({ context: c.name })} ${c.desiredReplicas}`))
    family('monoripper_context_replicas_ready', 'gauge', 'Ready replicas per context.', gauges.contexts.map(c => `monoripper_context_replicas_ready${labels({ context: c.name })} ${c.readyReplicas}`))
    family('monoripper_context_restarts', 'gauge', 'Automatic recoveries in the current restart budget window.', gauges.contexts.map(c => `monoripper_context_restarts${labels({ context: c.name })} ${c.restarts}`))
    family('monoripper_http_in_flight', 'gauge', 'Requests whose response body is still open.', gauges.contexts.map(c => `monoripper_http_in_flight${labels({ context: c.name })} ${c.inFlight}`))
    family('monoripper_http_requests_total', 'counter', 'Gateway responses by owner context, method and status.', [...this.requests].map(([key, value]) => {
      const [context, method, status] = key.split('\0') as [string, string, string]
      return `monoripper_http_requests_total${labels({ context, method, status })} ${value}`
    }))
    family('monoripper_gateway_errors_total', 'counter', 'Responses generated by the gateway itself.', [...this.errors].map(([key, value]) => {
      const [context, code] = key.split('\0') as [string, string]
      return `monoripper_gateway_errors_total${labels({ context, code })} ${value}`
    }))
    family('monoripper_http_request_duration_seconds', 'histogram', 'Time until upstream response headers.', [...this.durations].flatMap(([context, h]) => [
      ...buckets.map((bound, index) => `monoripper_http_request_duration_seconds_bucket${labels({ context, le: String(bound) })} ${h.counts[index]}`),
      `monoripper_http_request_duration_seconds_bucket${labels({ context, le: '+Inf' })} ${h.count}`,
      `monoripper_http_request_duration_seconds_sum${labels({ context })} ${h.sum}`,
      `monoripper_http_request_duration_seconds_count${labels({ context })} ${h.count}`,
    ]))
    const families = new Map<string, Family>()
    await Promise.all(targets.map(async target => {
      const text = await scrape(target)
      if (text === undefined) this.scrapeErrors.set(target.context, (this.scrapeErrors.get(target.context) ?? 0) + 1)
      else if (!merge(families, text, { context: target.context, worker: String(target.pid) })) this.scrapeErrors.set(target.context, (this.scrapeErrors.get(target.context) ?? 0) + 1)
    }))
    family('monoripper_worker_scrape_errors_total', 'counter', 'Worker metric scrapes that failed or returned invalid exposition.', [...this.scrapeErrors].map(([context, value]) => `monoripper_worker_scrape_errors_total${labels({ context })} ${value}`))
    for (const [name, value] of families) {
      if (value.help !== undefined) out.push(`# HELP ${name} ${value.help}`)
      out.push(`# TYPE ${name} ${value.type}`, ...value.samples)
    }
    return out.join('\n') + '\n'
  }
}

async function scrape(target: ScrapeTarget): Promise<string | undefined> {
  try {
    const response = await fetch(`http://127.0.0.1:${target.port}/`, {
      headers: { 'x-monoripper-token': target.token, 'x-monoripper-metrics': '1' }, signal: AbortSignal.timeout(2000), proxy: '',
    })
    if (response.status === 204) return ''
    if (response.status !== 200) return undefined
    const text = await response.text()
    return text.length > maxWorkerBytes ? undefined : text
  } catch { return undefined }
}

/** Splits `name{labels} value` respecting quoted label values. */
function parseSample(line: string): { name: string; labels: string; rest: string } | undefined {
  const brace = line.indexOf('{')
  const space = line.indexOf(' ')
  if (brace < 0 || (space >= 0 && space < brace)) {
    if (space < 0) return undefined
    return { name: line.slice(0, space), labels: '', rest: line.slice(space) }
  }
  let quoted = false
  for (let index = brace + 1; index < line.length; index++) {
    const char = line[index]
    if (quoted && char === '\\') { index++; continue }
    if (char === '"') quoted = !quoted
    else if (char === '}' && !quoted) return { name: line.slice(0, brace), labels: line.slice(brace + 1, index).trim().replace(/,$/, ''), rest: line.slice(index + 1) }
  }
  return undefined
}

/** Adds runtime labels; worker exposition cannot claim monoripper_* names or the injected labels. */
export function merge(families: Map<string, Family>, text: string, extra: Record<string, string>): boolean {
  const injected = Object.entries(extra).map(([key, value]) => `${key}="${escape(value)}"`).join(',')
  const local = new Map<string, Family>()
  let current: string | undefined
  for (const raw of text.split('\n')) {
    const line = raw.trim()
    if (!line) continue
    if (line.startsWith('#')) {
      const [, kind, name, ...rest] = line.split(' ')
      if ((kind !== 'HELP' && kind !== 'TYPE') || !name || !metricName.test(name) || name.startsWith('monoripper_')) continue
      const entry = local.get(name) ?? { type: 'untyped', samples: [] }
      if (kind === 'HELP') entry.help = rest.join(' ')
      else entry.type = rest[0] ?? 'untyped'
      local.set(name, entry)
      current = name
      continue
    }
    const sample = parseSample(line)
    if (!sample || !metricName.test(sample.name) || sample.name.startsWith('monoripper_')) return false
    if (/(^|,)\s*(context|worker)\s*=/.test(sample.labels)) return false
    const owner = current && sample.name.startsWith(current) ? current : sample.name
    const entry = local.get(owner) ?? { type: 'untyped', samples: [] }
    entry.samples.push(`${sample.name}{${injected}${sample.labels ? ',' + sample.labels : ''}}${sample.rest}`)
    local.set(owner, entry)
  }
  for (const [name, entry] of local) if (families.has(name) && families.get(name)!.type !== entry.type) return false
  for (const [name, entry] of local) {
    const existing = families.get(name)
    if (existing) existing.samples.push(...entry.samples); else families.set(name, entry)
  }
  return true
}
